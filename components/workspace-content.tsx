// 新的数据结构：直接从 Markdown 解析
interface MarkdownOutlineItem {
  id: string
  lineNumber: number  // 在 Markdown 中的行号（从0开始）
  level: number       // 1-5 (#, ##, ###, ####, #####)
  content: string     // 标题或正文内容（去除 # 符号和编号）
  rawLine: string     // 原始 Markdown 行（包含 # 符号和编号）
  hasBody: boolean    // 是否有正文内容（#####）
  bodyLineNumber?: number  // 正文内容所在的行号（如果有）
  bodyContent?: string     // 正文内容（如果有）
}

